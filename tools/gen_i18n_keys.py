#!/usr/bin/env python3
"""Generate the typed translation-key enum from the English resources.

Run from the workspace root:

    python3 tools/gen_i18n_keys.py

Reads ``crates/luatools-i18n/locales/Strings.resx`` and rewrites
``crates/luatools-i18n/src/keys.rs``. The generated file is committed so the UI can be grepped
without a build step; the translation tables themselves are compiled by ``build.rs``.
"""

from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESX = ROOT / "crates/luatools-i18n/locales/Strings.resx"
OUT = ROOT / "crates/luatools-i18n/src/keys.rs"

KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
    "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
    "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe",
    "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do",
    "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
}


def ident(name: str) -> str:
    cleaned = re.sub(r"[^0-9A-Za-z_]", "_", name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"K_{cleaned}"
    if cleaned in KEYWORDS:
        cleaned = f"{cleaned}_"
    return cleaned


def main() -> int:
    tree = ET.parse(RESX)
    entries = []
    seen = set()
    for data in tree.getroot().findall("data"):
        name = data.get("name")
        value = data.findtext("value") or ""
        if not name:
            continue
        variant = ident(name)
        if variant in seen:
            print(f"duplicate key after sanitizing: {name}", file=sys.stderr)
            return 1
        seen.add(variant)
        entries.append((variant, name, value.replace("\r", "").strip()))

    lines = [
        "//! Typed translation keys.",
        "//!",
        "//! Generated by `tools/gen_i18n_keys.py` from `locales/Strings.resx`. Do not edit by hand;",
        "//! add the resource entry to the resx files and re-run the generator.",
        "",
        "#![allow(non_camel_case_types)]",
        "",
        "use serde::{Deserialize, Serialize};",
        "",
        "/// One localized resource.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]",
        "pub enum Key {",
    ]
    for variant, name, value in entries:
        doc = value.replace("\\", "\\\\").replace("\n", " ")
        if len(doc) > 110:
            doc = doc[:107] + "..."
        lines.append(f"    /// `{name}`: {doc}")
        lines.append(f"    {variant},")
    lines += [
        "}",
        "",
        "impl Key {",
        "    /// Every key, ordered by name.",
        "    pub const ALL: &'static [Self] = &[",
    ]
    for variant, _, _ in entries:
        lines.append(f"        Self::{variant},")
    lines += [
        "    ];",
        "",
        "    /// The resource name as written in the `.resx` files.",
        "    #[must_use]",
        "    pub const fn resource_name(self) -> &'static str {",
        "        match self {",
    ]
    for variant, name, _ in entries:
        lines.append(f'            Self::{variant} => "{name}",')
    lines += [
        "        }",
        "    }",
        "",
        "    /// The English text, used as the fallback for every locale and by tests.",
        "    #[must_use]",
        "    pub const fn english(self) -> &'static str {",
        "        match self {",
    ]
    for variant, _, value in entries:
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'            Self::{variant} => "{escaped}",')
    lines += ["        }", "    }", "}", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} with {len(entries)} keys")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
