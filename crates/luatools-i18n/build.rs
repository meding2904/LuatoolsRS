//! Generates `$OUT_DIR/tables.rs` from the `.resx` resources in `locales/`.
//!
//! Each translated locale (`Strings.<tag>.resx`) becomes one statically sorted
//! `(&str, &str)` table of `(resource_name, text)` pairs. Sorting happens here, at build time,
//! so `Translator::t` can binary-search at runtime without parsing XML or touching the disk.
//!
//! This is deliberately a tiny scanner rather than a general XML parser: RESX files are
//! machine-written and only the `<data name=".."><value>..</value></data>` entries matter.
//!
//! # Failure policy
//!
//! A malformed resource file is a packaging bug. Falling back to English for the affected file
//! would ship a silently half-translated UI, so the script emits a `cargo:warning` with the
//! offending file and then panics with the same message to fail the build loudly. Recoverable
//! problems (missing keys, extra keys, duplicate names, unknown locale files) only produce
//! warnings and are covered by the crate's parity tests.

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

/// The English (neutral) resource file; its keys define the expected key set.
const ENGLISH_FILE: &str = "Strings.resx";

/// Translated locales, as `(BCP-47 tag, luatools_core::Locale variant)`.
///
/// The order matches `Locale::ALL` so the generated match arms are easy to compare against
/// `luatools-core`. A locale added to the enum without an entry here fails to compile in
/// `lib.rs` because the generated `table` match is exhaustive.
const LOCALES: &[(&str, &str)] = &[
    ("ar", "Ar"),
    ("bg", "Bg"),
    ("cs", "Cs"),
    ("da", "Da"),
    ("de", "De"),
    ("el", "El"),
    ("es", "Es"),
    ("es-419", "Es419"),
    ("fi", "Fi"),
    ("fr", "Fr"),
    ("hu", "Hu"),
    ("id", "Id"),
    ("it", "It"),
    ("ja", "Ja"),
    ("ko", "Ko"),
    ("nb", "Nb"),
    ("nl", "Nl"),
    ("pl", "Pl"),
    ("pt-BR", "PtBr"),
    ("pt-PT", "PtPt"),
    ("ro", "Ro"),
    ("ru", "Ru"),
    ("sv", "Sv"),
    ("th", "Th"),
    ("tr", "Tr"),
    ("uk", "Uk"),
    ("vi", "Vi"),
    ("zh-Hans", "ZhHans"),
    ("zh-Hant", "ZhHant"),
];

/// One `<data>` entry from a RESX file.
struct Entry {
    /// The resource name (`<data name="...">`), XML-decoded.
    name: String,
    /// The `<value>` text, XML-decoded.
    value: String,
}

fn main() {
    if let Err(problem) = run() {
        println!("cargo:warning=luatools-i18n: {problem}");
        // See the module docs: a broken resource file must not degrade into English fallback.
        panic!("luatools-i18n: {problem}");
    }
}

fn run() -> Result<(), String> {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR")
        .map_err(|error| format!("CARGO_MANIFEST_DIR is unavailable: {error}"))?;
    let locales_dir = PathBuf::from(manifest_dir).join("locales");

    println!("cargo:rerun-if-changed=locales");
    println!("cargo:rerun-if-changed=build.rs");

    warn_about_unknown_files(&locales_dir)?;

    let english_path = locales_dir.join(ENGLISH_FILE);
    println!("cargo:rerun-if-changed={}", english_path.display());
    let english = read_resx(&english_path)?;
    let english_names: BTreeSet<String> = english.iter().map(|entry| entry.name.clone()).collect();
    warn_about_duplicates(&english_path, &english);

    let mut tables = Vec::with_capacity(LOCALES.len());
    let mut generated = String::with_capacity(1 << 20);
    generated.push_str("// @generated by `crates/luatools-i18n/build.rs`. Do not edit by hand.\n");
    generated.push_str("use luatools_core::Locale;\n\n");

    for &(tag, variant) in LOCALES {
        let path = locales_dir.join(format!("Strings.{tag}.resx"));
        println!("cargo:rerun-if-changed={}", path.display());
        let entries = read_resx(&path)?;
        warn_about_duplicates(&path, &entries);

        // A BTreeMap sorts by resource name and keeps one value per name.
        let mut table: BTreeMap<String, String> = BTreeMap::new();
        for entry in entries {
            // Duplicates were already reported by `warn_about_duplicates`; the later value wins.
            table.insert(entry.name, entry.value);
        }
        report_key_differences(tag, &english_names, &table);

        let static_name = static_name(tag);
        generated.push_str("/// Translations for `");
        generated.push_str(tag);
        generated.push_str("`, sorted by resource name.\n");
        generated.push_str("pub static ");
        generated.push_str(&static_name);
        generated.push_str(": &[(&str, &str)] = &[\n");
        for (name, value) in &table {
            generated.push_str("    (");
            push_rust_literal(&mut generated, name);
            generated.push_str(", ");
            push_rust_literal(&mut generated, value);
            generated.push_str("),\n");
        }
        generated.push_str("];\n\n");

        tables.push((variant, static_name, table.len()));
    }

    generated.push_str("/// The sorted translation table for `locale`.\n");
    generated.push_str("///\n");
    generated.push_str("/// English is empty: `Key::english` is its fallback.\n");
    generated
        .push_str("pub fn table(locale: Locale) -> &'static [(&'static str, &'static str)] {\n");
    generated.push_str("    match locale {\n");
    generated.push_str("        Locale::En => &[],\n");
    for (variant, static_name, _) in &tables {
        generated.push_str("        Locale::");
        generated.push_str(variant);
        generated.push_str(" => ");
        generated.push_str(static_name);
        generated.push_str(",\n");
    }
    generated.push_str("    }\n");
    generated.push_str("}\n");

    let out_dir =
        env::var("OUT_DIR").map_err(|error| format!("OUT_DIR is unavailable: {error}"))?;
    let out_path = PathBuf::from(out_dir).join("tables.rs");
    fs::write(&out_path, generated)
        .map_err(|error| format!("failed to write `{}`: {error}", out_path.display()))?;

    Ok(())
}

/// Warns when a `Strings.*.resx` file has no matching entry in [`LOCALES`].
fn warn_about_unknown_files(locales_dir: &Path) -> Result<(), String> {
    let entries = fs::read_dir(locales_dir).map_err(|error| {
        format!(
            "failed to read locale directory `{}`: {error}",
            locales_dir.display()
        )
    })?;
    let known: BTreeSet<&str> = LOCALES.iter().map(|(tag, _)| *tag).collect();
    for entry in entries {
        let entry = entry.map_err(|error| {
            format!(
                "failed to enumerate locale directory `{}`: {error}",
                locales_dir.display()
            )
        })?;
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            continue;
        };
        let Some(tag) = name
            .strip_prefix("Strings.")
            .and_then(|rest| rest.strip_suffix(".resx"))
        else {
            continue;
        };
        if !known.contains(tag) {
            println!(
                "cargo:warning=luatools-i18n: `{name}` does not match any entry in build.rs \
                 LOCALES; it is ignored"
            );
        }
    }
    Ok(())
}

/// Warns about duplicate resource names in a file.
fn warn_about_duplicates(path: &Path, entries: &[Entry]) {
    let mut seen = BTreeSet::new();
    for entry in entries {
        if !seen.insert(entry.name.as_str()) {
            println!(
                "cargo:warning=luatools-i18n: `{}` defines `{}` more than once; the later value is used",
                path.display(),
                entry.name
            );
        }
    }
}

/// Emits a warning when a locale's key set differs from English's.
fn report_key_differences(tag: &str, english: &BTreeSet<String>, table: &BTreeMap<String, String>) {
    let missing: Vec<&str> = english
        .iter()
        .filter(|name| !table.contains_key(name.as_str()))
        .map(String::as_str)
        .collect();
    let extra: Vec<&str> = table
        .keys()
        .filter(|name| !english.contains(name.as_str()))
        .map(String::as_str)
        .collect();
    if missing.is_empty() && extra.is_empty() {
        return;
    }
    println!(
        "cargo:warning=luatools-i18n: locale `{tag}` has {} missing key(s) and {} extra key(s); \
         missing: [{}]; extra: [{}]",
        missing.len(),
        extra.len(),
        preview(&missing),
        preview(&extra)
    );
}

/// Joins the first few names for a readable warning.
fn preview(names: &[&str]) -> String {
    const LIMIT: usize = 8;
    let mut text = names
        .iter()
        .take(LIMIT)
        .copied()
        .collect::<Vec<_>>()
        .join(", ");
    if names.len() > LIMIT {
        text.push_str(", ...");
    }
    text
}

/// Turns `es-419` into `TABLE_ES_419`.
fn static_name(tag: &str) -> String {
    let mut name = String::with_capacity(tag.len() + 6);
    name.push_str("TABLE_");
    for character in tag.chars() {
        if character.is_ascii_alphanumeric() {
            name.push(character.to_ascii_uppercase());
        } else {
            name.push('_');
        }
    }
    name
}

/// Appends `value` as a Rust string literal.
fn push_rust_literal(out: &mut String, value: &str) {
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            character if character.is_control() => {
                out.push_str(&format!("\\u{{{:x}}}", character as u32));
            }
            character => out.push(character),
        }
    }
    out.push('"');
}

/// Reads and parses one RESX file, adding the file name to any error.
fn read_resx(path: &Path) -> Result<Vec<Entry>, String> {
    let text = fs::read_to_string(path)
        .map_err(|error| format!("failed to read `{}`: {error}", path.display()))?;
    parse_resx(&text)
        .map_err(|problem| format!("malformed resource file `{}`: {problem}", path.display()))
}

/// Extracts every text `<data name="...">` entry from RESX source.
fn parse_resx(source: &str) -> Result<Vec<Entry>, String> {
    let mut entries = Vec::new();
    let mut cursor = 0;
    while let Some(start) = find_element(source, "data", cursor) {
        let tag_end = find_tag_end(source, start)?;
        let raw_tag = &source[start + "<data".len()..tag_end];
        let attributes = parse_attributes(raw_tag)?;
        let name = attributes
            .iter()
            .find(|(key, _)| key == "name")
            .map(|(_, value)| value.clone())
            .ok_or_else(|| "`<data>` element without a `name` attribute".to_owned())?;
        let self_closing = raw_tag.trim_end().ends_with('/');
        let body_start = tag_end + 1;
        if self_closing {
            cursor = body_start;
            continue;
        }
        let close = find_close_tag(source, "data", body_start)?;
        let body = &source[body_start..close];
        cursor = close + "</data>".len();

        // Typed resources (images, binaries) have no translatable text.
        if attributes.iter().any(|(key, _)| key == "type") {
            continue;
        }
        // A missing `<value>` means "no translation"; the runtime falls back to English.
        if let Some(value) = extract_value(body)? {
            entries.push(Entry { name, value });
        }
    }
    Ok(entries)
}

/// Finds `<name` at or after `from`, requiring a tag boundary after the element name.
fn find_element(source: &str, name: &str, from: usize) -> Option<usize> {
    let needle = format!("<{name}");
    let mut cursor = from;
    while let Some(relative) = source.get(cursor..)?.find(&needle) {
        let start = cursor + relative;
        match source[start + needle.len()..].chars().next() {
            Some(character)
                if character.is_whitespace() || character == '>' || character == '/' =>
            {
                return Some(start);
            }
            Some(_) => cursor = start + needle.len(),
            None => return None,
        }
    }
    None
}

/// Finds the `</name>` closing tag at or after `from`.
fn find_close_tag(source: &str, name: &str, from: usize) -> Result<usize, String> {
    let needle = format!("</{name}>");
    source
        .get(from..)
        .and_then(|rest| rest.find(&needle))
        .map(|relative| from + relative)
        .ok_or_else(|| format!("unterminated `<{name}>` element"))
}

/// Returns the byte offset of the `>` that closes the tag starting at `start`.
fn find_tag_end(source: &str, start: usize) -> Result<usize, String> {
    let mut quote = None;
    // Skip the opening `<` so it is not mistaken for a nested tag.
    let rest = source
        .get(start.saturating_add(1)..)
        .ok_or_else(|| "tag start is out of bounds".to_owned())?;
    for (offset, character) in rest.char_indices() {
        match quote {
            Some(delimiter) => {
                if character == delimiter {
                    quote = None;
                }
            }
            None => match character {
                '"' | '\'' => quote = Some(character),
                '>' => return Ok(start.saturating_add(1).saturating_add(offset)),
                '<' => return Err("nested `<` inside a tag".to_owned()),
                _ => {}
            },
        }
    }
    Err("unterminated tag".to_owned())
}

/// Parses `key="value"` pairs from the inside of a tag (without `<data` / `>`).
fn parse_attributes(tag: &str) -> Result<Vec<(String, String)>, String> {
    let bytes = tag.as_bytes();
    let mut attributes = Vec::new();
    let mut cursor = 0;
    while cursor < bytes.len() {
        while cursor < bytes.len() && bytes[cursor].is_ascii_whitespace() {
            cursor += 1;
        }
        if cursor >= bytes.len() || bytes[cursor] == b'/' {
            break;
        }
        let name_start = cursor;
        while cursor < bytes.len() && !bytes[cursor].is_ascii_whitespace() && bytes[cursor] != b'='
        {
            cursor += 1;
        }
        let name = &tag[name_start..cursor];
        while cursor < bytes.len() && bytes[cursor].is_ascii_whitespace() {
            cursor += 1;
        }
        if cursor >= bytes.len() || bytes[cursor] != b'=' {
            return Err(format!("attribute `{name}` has no value"));
        }
        cursor += 1;
        while cursor < bytes.len() && bytes[cursor].is_ascii_whitespace() {
            cursor += 1;
        }
        let Some(&quote) = bytes.get(cursor) else {
            return Err(format!("attribute `{name}` has no value"));
        };
        if quote != b'"' && quote != b'\'' {
            return Err(format!("attribute `{name}` is not quoted"));
        }
        cursor += 1;
        let value_start = cursor;
        while cursor < bytes.len() && bytes[cursor] != quote {
            cursor += 1;
        }
        if cursor >= bytes.len() {
            return Err(format!("unterminated value for attribute `{name}`"));
        }
        let value = &tag[value_start..cursor];
        cursor += 1;
        attributes.push((name.to_owned(), decode_entities(value)?));
    }
    Ok(attributes)
}

/// Extracts the `<value>` text from a `<data>` body.
fn extract_value(body: &str) -> Result<Option<String>, String> {
    let Some(start) = find_element(body, "value", 0) else {
        return Ok(None);
    };
    let tag_end = find_tag_end(body, start)?;
    if body[start..tag_end].trim_end().ends_with('/') {
        return Ok(Some(String::new()));
    }
    let content_start = tag_end + 1;
    let close = find_close_tag(body, "value", content_start)?;
    decode_entities(&body[content_start..close]).map(Some)
}

/// Decodes the five XML entities plus numeric character references.
fn decode_entities(input: &str) -> Result<String, String> {
    if !input.contains('&') {
        return Ok(input.to_owned());
    }
    let mut decoded = String::with_capacity(input.len());
    let mut rest = input;
    while let Some(ampersand) = rest.find('&') {
        decoded.push_str(&rest[..ampersand]);
        let after = &rest[ampersand + 1..];
        let Some(semicolon) = after.find(';') else {
            return Err("unterminated XML entity".to_owned());
        };
        let entity = &after[..semicolon];
        match entity {
            "amp" => decoded.push('&'),
            "lt" => decoded.push('<'),
            "gt" => decoded.push('>'),
            "quot" => decoded.push('"'),
            "apos" => decoded.push('\''),
            _ => {
                let code_point = entity
                    .strip_prefix("#x")
                    .or_else(|| entity.strip_prefix("#X"))
                    .and_then(|hex| u32::from_str_radix(hex, 16).ok())
                    .or_else(|| {
                        entity
                            .strip_prefix('#')
                            .and_then(|decimal| decimal.parse::<u32>().ok())
                    });
                let Some(character) = code_point.and_then(char::from_u32) else {
                    return Err(format!("unsupported XML entity `&{entity};`"));
                };
                decoded.push(character);
            }
        }
        rest = &after[semicolon + 1..];
    }
    decoded.push_str(rest);
    Ok(decoded)
}
